// Write web/src/codeprints.ts: for each production contract, the hash of its runtime code from this repository's build,
// with immutables zeroed and the metadata trailer removed (see agent/codecheck.ts). The app and `npm run check-code`
// compare deployed code against these. CI regenerates the file and fails if it differs, so it always matches the source.
//
//   npx hardhat compile && node scripts/export-codeprints.mjs

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const CONTRACTS = {
  PilotVault: "contracts/PilotVault.sol",
  PilotVaultFactory: "contracts/PilotVaultFactory.sol",
  PilotRegistry: "contracts/PilotRegistry.sol",
  MandateCredential: "contracts/MandateCredential.sol",
  PilotJournal: "contracts/PilotJournal.sol",
  PilotFundFactory: "contracts/PilotFundFactory.sol",
  PilotFund: "contracts/PilotFund.sol",
};

// The newest build that contains the vault: a clean compile leaves exactly one.
const dir = "artifacts/build-info";
const builds = readdirSync(dir)
  .map((f) => `${dir}/${f}`)
  .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)
  .map((f) => JSON.parse(readFileSync(f, "utf8")))
  .filter((b) => b.output?.contracts?.["contracts/PilotVault.sol"]);
if (!builds.length) throw new Error("No build found: run npx hardhat compile first.");
const build = builds[0];

const withoutMetadata = (bytes) => {
  const length = (bytes[bytes.length - 2] << 8) | bytes[bytes.length - 1];
  return length + 2 <= bytes.length ? bytes.slice(0, bytes.length - length - 2) : bytes;
};

// Every embedded metadata block's source hash, blanked (see agent/codecheck.ts: a factory carries its child's).
const IPFS_TAG = [0xa2, 0x64, 0x69, 0x70, 0x66, 0x73, 0x58, 0x22];
const SOLC_TAG = [0x64, 0x73, 0x6f, 0x6c, 0x63, 0x43];
const blankEmbeddedMetadata = (bytes) => {
  const at = (i, tag) => tag.every((b, k) => bytes[i + k] === b);
  for (let i = 0; i + IPFS_TAG.length + 34 + SOLC_TAG.length <= bytes.length; i++) {
    if (at(i, IPFS_TAG) && at(i + IPFS_TAG.length + 34, SOLC_TAG)) bytes.fill(0, i + IPFS_TAG.length, i + IPFS_TAG.length + 34);
  }
};

const prints = {};
for (const [name, source] of Object.entries(CONTRACTS)) {
  const deployed = build.output.contracts[source][name].evm.deployedBytecode;
  const immutables = Object.values(deployed.immutableReferences ?? {})
    .flat()
    .map((r) => [r.start, r.length])
    .sort((a, b) => a[0] - b[0]);
  const bytes = Uint8Array.from(Buffer.from(deployed.object, "hex"));
  for (const [start, length] of immutables) bytes.fill(0, start, start + length);
  blankEmbeddedMetadata(bytes);
  prints[name] = { hash: keccak256(withoutMetadata(bytes)), immutables };
}

const body = Object.entries(prints)
  .map(([name, p]) => `  ${name}: {\n    hash: "${p.hash}",\n    immutables: [${p.immutables.map(([s, l]) => `[${s}, ${l}]`).join(", ")}],\n  },`)
  .join("\n");
writeFileSync(
  "web/src/codeprints.ts",
  `// Generated by scripts/export-codeprints.mjs from this repository's build (solc ${build.solcVersion}). Do not edit.\n` +
    `import type { CodePrint } from "../../agent/codecheck";\n\n` +
    `export const SOLC_VERSION = "${build.solcVersion}";\n\n` +
    `export const CODE_PRINTS = {\n${body}\n} as const satisfies Record<string, CodePrint>;\n`,
);
console.log(`wrote web/src/codeprints.ts (${Object.keys(prints).length} contracts, solc ${build.solcVersion})`);
